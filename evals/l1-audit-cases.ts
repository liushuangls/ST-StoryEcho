import type { TavernChatMessage } from '../src/core/types';
import { makeRubric } from './cases';
import type { PromptEvalCase, PromptEvalHardCheck } from './types';

function message(
  speaker: 'user' | 'assistant',
  name: string,
  mes: string,
): TavernChatMessage {
  return { is_user: speaker === 'user', is_system: false, name, mes };
}

function worldBackground(text: string): string {
  return `<story_echo_world_background>\n${text.trim()}\n</story_echo_world_background>`;
}

function all(id: string, description: string, ...needles: string[]): PromptEvalHardCheck {
  return { id, description, mode: 'all', needles };
}

function any(id: string, description: string, ...needles: string[]): PromptEvalHardCheck {
  return { id, description, mode: 'any', needles };
}


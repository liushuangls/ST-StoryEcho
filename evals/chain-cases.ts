import type { TavernChatMessage } from '../src/core/types';

export interface ChainProbe {
  id: string;
  question: string;
  choices: readonly string[];
  correctChoice: number;
}

export interface PromptEvalChainCase {
  id: string;
  name: string;
  identity: { userUiPersona: string; assistantCharacter: string };
  worldBackground: string;
  batches: readonly (readonly TavernChatMessage[])[];
  probes: readonly ChainProbe[];
}

function batch(user: string, character: string, atmosphere: readonly string[], turns: readonly (readonly [string, string])[]): TavernChatMessage[] {
  return turns.flatMap(([question, response], index) => [
    { is_user: true, name: user, mes: question },
    { is_user: false, name: character, mes: [atmosphere[index % atmosphere.length], response].join('\n\n') },
  ]);
}

